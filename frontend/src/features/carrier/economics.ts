import type { 톤급 } from '../../lib/types'
import type { 추천콜상세 } from './carrierTypes'

/**
 * 경유 1L 가격.
 *
 * ⚠ 출처 미확정. PROJECT_KNOWLEDGE.md 에 이 값이 없다(문서 전체에 "1503" 없음).
 */
export const 경유_원_per_L = 1503

/** ⚠ 출처 미확정. 업계 평균 추정치이며 실서비스에서는 차량별 실연비로 교체해야 한다 */
export const 연비_km_per_L: Record<톤급, { 적재: number; 공차: number }> = {
  5: { 적재: 5.5, 공차: 7.0 },
  11: { 적재: 4.0, 공차: 5.0 },
  25: { 적재: 3.2, 공차: 4.0 },
}

/**
 * 톤급별 거리당 배출계수(kg CO₂/km). TTW(연소) 기준.
 *
 * ⚠ 출처 미확정 — 6개 값 전부 근거 문서가 없다. 상단 주석 참고.
 * PROJECT_KNOWLEDGE.md 는 EF_loaded·EF_empty 를 변수로만 정의한다.
 */
export const 배출계수_kg_per_km: Record<톤급, { 적재: number; 공차: number }> = {
  5: { 적재: 0.474, 공차: 0.373 },
  11: { 적재: 0.652, 공차: 0.522 },
  25: { 적재: 0.815, 공차: 0.652 },
}

/**
 * 공차 이동 평균 속도(km/h).
 *
 * 백엔드가 공차 소요시간을 주지 않아서 거리에서 환산한다.
 * 시간당 실수령을 계산할 때만 쓰이고 금액에는 영향을 주지 않는다.
 */
export const 공차_평균속도_kmh = 50

export interface 수익분해 {
  운임: number
  유류비_적재: number
  유류비_공차: number
  톨비: number
  /** 운임 − 유류비(적재) − 유류비(공차) − 톨비 */
  실수령: number
  /** 적재 소요 + 공차 이동 시간 */
  총소요_h: number
  /** 실수령 ÷ 총소요_h. 표면 운임이 높은 콜이 여기서 뒤집히곤 한다 */
  시간당_실수령: number
  /** 적재 + 공차 구간 TTW 배출량 */
  탄소배출_kg: number
}

function 유류비(거리km: number, 연비: number): number {
  if (거리km <= 0 || 연비 <= 0) return 0
  return Math.round((거리km / 연비) * 경유_원_per_L)
}

/**
 * 콜 한 건의 수익 분해.
 *
 * 톤급은 콜이 아니라 차주의 차량 프로필에서 온다 — `운송인추천콜` 에 톤급이 없기 때문이다.
 */
export function 수익분해계산(콜: 추천콜상세, 톤급값: 톤급): 수익분해 {
  const 연비 = 연비_km_per_L[톤급값]
  const 계수 = 배출계수_kg_per_km[톤급값]

  const 유류비_적재 = 유류비(콜.거리km, 연비.적재)
  const 유류비_공차 = 유류비(콜.공차거리km, 연비.공차)
  const 실수령 = 콜.예측_운임 - 유류비_적재 - 유류비_공차 - 콜.톨비

  const 공차_h = 콜.공차거리km / 공차_평균속도_kmh
  const 총소요_h = 콜.표준소요_h + 공차_h

  return {
    운임: 콜.예측_운임,
    유류비_적재,
    유류비_공차,
    톨비: 콜.톨비,
    실수령,
    총소요_h,
    시간당_실수령: 총소요_h > 0 ? Math.round(실수령 / 총소요_h) : 0,
    탄소배출_kg: Math.round((콜.거리km * 계수.적재 + 콜.공차거리km * 계수.공차) * 10) / 10,
  }
}

/**
 * 도착지가 귀가 희망 지역인가.
 *
 * 지오코딩 없이 문자열 앞부분만 본다. 데모 범위에서는 충분하고,
 * 실서비스에서는 행정구역 코드로 바꿔야 한다.
 */
export function 귀가가능한가(도착지: string, 귀가희망지역: string): boolean {
  if (귀가희망지역.trim() === '') return false
  return 도착지.startsWith(귀가희망지역.trim())
}

