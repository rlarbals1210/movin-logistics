/**
 * 운송인 실수령 계산.
 *
 * 순수 함수만 둔다. 화면·fetch 를 여기서 부르지 않는다.
 *
 * ── 상수 출처 ───────────────────────────────────────────────
 * 출처는 `docs/reference/hack/carbon-emissions-methodology.docx` 다.
 * PROJECT_KNOWLEDGE.md 에는 없어서 한동안 "출처 미확정" 으로 적혀 있었지만,
 * 그 문서가 폐기한 건 docx 의 **산정식(방식 A/B)과 12,000건 데모 결과**이지
 * 계수가 아니다(PROJECT_KNOWLEDGE.md 199줄).
 *
 *   · 경유 배출계수 2.609 kg CO₂/L — 「에너지법 시행규칙」 별표12 (공식)
 *   · 경유가 1,503 원/L — 한국에너지공단 2024 (공식)
 *   · 톤급별 연비 — ⚠ **업계 평균 추정치.** 국내 화물차 톤급별 공식 연비 통계가 없다.
 *
 * 즉 "연료 단가·배출계수는 공식, 연비는 가정" 이다. 연비가 유류비와 배출계수 양쪽에
 * 물려 있으므로, 이 모듈이 낸 금액·배출량을 화면에 띄울 때는 추정치임을 함께 표시한다.
 * 실서비스에서는 차량별 실연비·실연료로 대체하면 완전 실측이 된다.
 *
 * ── 기획안 대표 데모와의 차이 (원인 규명 완료) ──────────────
 * 최종 기획안의 대표 데모는 `부산→서울 운임 47만 / 유류 7.4만 / 실수령 38.2만` 이다.
 * 아래 상수로 부산→서울 약 400km, 11톤을 계산하면 유류비가 15.0만원이다.
 * (400 ÷ 4.0km/L × 1,503원 = 150,300원) — 기획안 수치의 2.03배.
 *
 * 역산하면 원인은 유가나 연비가 아니라 **거리**다.
 *   · 연비 4.0 · 유가 1,503 고정 → 74,000원이 나오려면 거리가 197km 여야 한다
 *   · 거리 400km 고정 시 필요 연비는 8.12km/L (11톤 트럭에 비현실적)
 *   · 거리 400km 고정 시 필요 유가는 740원/L (비현실적)
 *
 * 197km 는 400km 의 절반이다. 기획안이 부산→서울을 200km 로 잡았거나
 * 편도/왕복을 혼동한 것으로 보인다. 따라서 기획안 수치를 쓰지 않고
 * 이 모듈 기준으로 발표 대표 수치를 다시 뽑는다(docs/PROGRESS.md 11:49 항목).
 */
import { 배출계수_kg_per_km } from '../../lib/emissions'
import type { 톤급 } from '../../lib/types'
import type { 추천콜상세 } from './carrierTypes'

/** 경유 1L 가격. 한국에너지공단 2024. */
export const 경유_원_per_L = 1503

/** ⚠ 업계 평균 추정치. 실서비스에서는 차량별 실연비로 교체해야 한다. */
export const 연비_km_per_L: Record<톤급, { 적재: number; 공차: number }> = {
  5: { 적재: 5.5, 공차: 7.0 },
  11: { 적재: 4.0, 공차: 5.0 },
  25: { 적재: 3.2, 공차: 4.0 },
}

/**
 * 공차 이동 평균 속도(km/h).
 *
 * 백엔드가 공차 소요시간을 주지 않아서 거리에서 환산한다.
 * 시간당 실수령을 계산할 때만 쓰이고 금액에는 영향을 주지 않는다.
 */
export const 공차_평균속도_kmh = 50

export interface 수익분해 {
  운임: number
  유류비_적재: number
  유류비_공차: number
  톨비: number
  /** 운임 − 유류비(적재) − 유류비(공차) − 톨비 */
  실수령: number
  /** 적재 소요 + 공차 이동 시간 */
  총소요_h: number
  /** 실수령 ÷ 총소요_h. 표면 운임이 높은 콜이 여기서 뒤집히곤 한다 */
  시간당_실수령: number
  /** 적재 + 공차 구간 TTW 배출량 */
  탄소배출_kg: number
}

function 유류비(거리km: number, 연비: number): number {
  if (거리km <= 0 || 연비 <= 0) return 0
  return Math.round((거리km / 연비) * 경유_원_per_L)
}

/**
 * 콜 한 건의 수익 분해.
 *
 * 톤급은 콜이 아니라 차주의 차량 프로필에서 온다 — `운송인추천콜` 에 톤급이 없기 때문이다.
 */
export function 수익분해계산(콜: 추천콜상세, 톤급값: 톤급): 수익분해 {
  const 연비 = 연비_km_per_L[톤급값]
  const 계수 = 배출계수_kg_per_km[톤급값]

  const 유류비_적재 = 유류비(콜.거리km, 연비.적재)
  const 유류비_공차 = 유류비(콜.공차거리km, 연비.공차)
  const 실수령 = 콜.예측_운임 - 유류비_적재 - 유류비_공차 - 콜.톨비

  const 공차_h = 콜.공차거리km / 공차_평균속도_kmh
  const 총소요_h = 콜.표준소요_h + 공차_h

  return {
    운임: 콜.예측_운임,
    유류비_적재,
    유류비_공차,
    톨비: 콜.톨비,
    실수령,
    총소요_h,
    시간당_실수령: 총소요_h > 0 ? Math.round(실수령 / 총소요_h) : 0,
    탄소배출_kg: Math.round((콜.거리km * 계수.적재 + 콜.공차거리km * 계수.공차) * 10) / 10,
  }
}

/**
 * 도착지가 귀가 희망 지역인가.
 *
 * 지오코딩 없이 문자열 앞부분만 본다. 데모 범위에서는 충분하고,
 * 실서비스에서는 행정구역 코드로 바꿔야 한다.
 */
export function 귀가가능한가(도착지: string, 귀가희망지역: string): boolean {
  if (귀가희망지역.trim() === '') return false
  return 도착지.startsWith(귀가희망지역.trim())
}

/**
 * dev 전용 자기점검.
 *
 * 테스트 러너가 없어서(package.json 미설치) 손계산 대조를 여기 남긴다.
 * CALL-1042(118.4km, 공차 12.5km, 운임 352,000, 톨비 6,800)를 11톤으로:
 *   유류비_적재 = 118.4 ÷ 4.0 × 1503 = 44,489
 *   유류비_공차 =  12.5 ÷ 5.0 × 1503 =  3,758
 *   실수령      = 352,000 − 44,489 − 3,758 − 6,800 = 296,953
 */
export function 자기점검(): void {
  if (!import.meta.env.DEV) return

  const 표본: 추천콜상세 = {
    콜ID: 'SELF-CHECK',
    출발지: '-',
    도착지: '-',
    거리km: 118.4,
    예측_운임: 352000,
    톨비: 6800,
    표준소요_h: 2.1,
    공차거리km: 12.5,
    복화가능성: 0,
    상차시각: '-',
    상차ISO: '2026-08-13T00:00:00+09:00',
    출발좌표: null,
    도착좌표: null,
    운행시간분: 126,
    유류비원: 44489,
    공차비원: 3758,
    예상실수령원: 296953,
    태그: [],
    경고: [],
    추천여부: false,
  }

  const 결과 = 수익분해계산(표본, 11)
  if (결과.실수령 !== 296953) {
    console.warn(`[economics] 실수령 자기점검 불일치: 296953 을 기대했는데 ${결과.실수령} 이다.`)
  }
}
