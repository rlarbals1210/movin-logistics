def coords(label: str | None) -> tuple[float, float] | None:
    """장소 라벨 → (위도, 경도). 표에 없으면 None — 호출부가 기존 고정값을 쓴다."""
    if not label:
        return None
    label = label.strip()
    if label in LOCATION_COORDS:
        return LOCATION_COORDS[label]
    대표지 = _권역_대표지.get(label)
    return LOCATION_COORDS.get(대표지) if 대표지 else None


def haversine_km(origin: tuple[float, float], destination: tuple[float, float]) -> float:
    """두 좌표 사이의 대권(직선) 거리 km."""
    lat1, lng1 = origin
    lat2, lng2 = destination
    dlat = radians(lat2 - lat1)
    dlng = radians(lng2 - lng1)
    a = sin(dlat / 2) ** 2 + cos(radians(lat1)) * cos(radians(lat2)) * sin(dlng / 2) ** 2
    return 2 * _지구반지름_km * asin(sqrt(a))


def road_distance_km(origin: tuple[float, float], destination: tuple[float, float]) -> float:
    """도로거리 근사값 km. 직선거리 × 도로계수, 소수 첫째 자리."""
    return round(haversine_km(origin, destination) * _도로계수, 1)
